import type { MonitorSlot, SystemMonitorTemplate } from "./types";

const SLOT_COUNT = 11;

/** 11枠に揃える。空の値はプロンプト生成時に省略される。 */
function slots(entries: Array<[string, string]>): MonitorSlot[] {
  const filled: MonitorSlot[] = entries.map(([label, default_value]) => ({
    label,
    default_value,
  }));
  while (filled.length < SLOT_COUNT) {
    filled.push({ label: `項目${filled.length + 1}`, default_value: "" });
  }
  return filled.slice(0, SLOT_COUNT);
}

